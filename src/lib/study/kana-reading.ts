/**
 * Trả về tập hợp các chữ Hán (Kanji) chính thức đã học trong chương trình
 * tính đến bài học cao nhất trong danh sách allowedBai.
 */
export function getAllowedKanjiChars(allowedBai?: number[]): Set<string> {
  const maxBai = allowedBai && allowedBai.length > 0 ? Math.max(...allowedBai) : 7;
  const list = alphabet.filter((g) => {
    if (g.type !== "kanji" || !g.row) return false;
    const m = g.row.match(/Bài (\d+)/);
    if (!m) return false;
    const b = parseInt(m[1], 10);
    return b <= maxBai;
  });
  return new Set(list.map((k) => k.char));
}

/**
 * Chuyển đổi các chữ Hán CHƯA HỌC trong văn bản thành Hiragana/Katakana,
 * đồng thời BẢO TỒN NGUYÊN VẸN các chữ Hán đã được học chính thức trong bài.
 */
export function replaceUntaughtKanjiWithKana(
  text: string,
  allowedChars: Set<string>,
): string {
  if (!text || !hasKanji(text)) return text;

  let result = text;
  // Lượt 1: Quét cụm từ và từ ghép dài nhất trước (ưu tiên độ chính xác cao)
  for (const [kanjiPhrase, kanaReading] of SORTED_ENTRIES) {
    if (!result.includes(kanjiPhrase)) continue;

    const pChars = kanjiPhrase.match(/[一-龯]/g) || [];
    const hasUntaught = pChars.some((c) => !allowedChars.has(c));

    if (hasUntaught) {
      result = result.replaceAll(kanjiPhrase, kanaReading);
    }
  }

  // Lượt 2: Quét đơn tự Hán tự chưa học còn sót lại
  if (hasKanji(result)) {
    let finalResult = "";
    for (const char of result) {
      if (/[一-龯]/.test(char) && !allowedChars.has(char)) {
        finalResult += KANJI_SINGLE_CHAR_MAP[char] || char;
      } else {
        finalResult += char;
      }
    }
    result = finalResult;
  }

  return result;
}

/**
 * Định dạng câu hỏi kiểm tra: Chuyển đổi toàn bộ chữ Hán chưa học trong đề bài,
 * phương án lựa chọn, đáp án đúng sang Hiragana/Katakana.
 */
export function formatExamQuestionKanji(
  q: ExamQuestion,
  allowedBai: number[],
): ExamQuestion {
  const allowedChars = getAllowedKanjiChars(allowedBai);

  const sentence = replaceUntaughtKanjiWithKana(q.sentence, allowedChars);
  const options = q.options.map((opt) => replaceUntaughtKanjiWithKana(opt, allowedChars));
  const answer = replaceUntaughtKanjiWithKana(q.answer, allowedChars);
  const prompt = replaceUntaughtKanjiWithKana(q.prompt, allowedChars);
  const promptJp = q.promptJp ? replaceUntaughtKanjiWithKana(q.promptJp, allowedChars) : q.promptJp;

  let explanation = q.explanation;
  if (explanation) {
    explanation = {
      ...explanation,
      grammar: explanation.grammar
        ? replaceUntaughtKanjiWithKana(explanation.grammar, allowedChars)
        : explanation.grammar,
      tips: explanation.tips
        ? replaceUntaughtKanjiWithKana(explanation.tips, allowedChars)
        : explanation.tips,
      reason: explanation.reason
        ? replaceUntaughtKanjiWithKana(explanation.reason, allowedChars)
        : explanation.reason,
    };
  }

  return {
    ...q,
    promptJp,
    prompt,
    sentence,
    options,
    answer,
    explanation,
  };
}

/**
 * Chuyển đổi một chuỗi tiếng Nhật có chứa Kanji thành phiên âm Hiragana/Katakana.
 * Giữ nguyên các ký tự đặc biệt, dấu câu, chỗ trống điền từ như （　　）hoặc 〔〕.
 */
export function toKana(text: string): string {
  if (!text || !hasKanji(text)) return text;

  let result = text;
  // Lượt 1: Cụm từ dài nhất trước
  for (const [kanjiPhrase, kanaReading] of SORTED_ENTRIES) {
    if (result.includes(kanjiPhrase)) {
      result = result.replaceAll(kanjiPhrase, kanaReading);
    }
    if (!hasKanji(result)) break;
  }

  // Lượt 2: Chữ Hán đơn lẻ còn sót lại
  if (hasKanji(result)) {
    let finalResult = "";
    for (const char of result) {
      if (/[一-龯]/.test(char)) {
        finalResult += KANJI_SINGLE_CHAR_MAP[char] || char;
      } else {
        finalResult += char;
      }
    }
    result = finalResult;
  }

  return result;
}

/**
 * Kiểm tra xem câu hỏi có phải là dạng dịch từ tiếng Việt sang tiếng Nhật hay không.
 * Các câu này có phần câu hỏi là tiếng Việt và đáp án là câu tiếng Nhật,
 * do đó tuyệt đối KHÔNG hiển thị Hiragana để tránh làm lộ đáp án.
 */
export function isViToJpQuestion(
  sentence?: string | null,
  question?: Partial<ExamQuestion> | null,
): boolean {
  if (sentence && sentence.startsWith("Dịch sang tiếng Nhật")) return true;
  if (sentence && !/[ぁ-んァ-ヶ一-龯]/.test(sentence)) return true;
  if (question?.id && (question.id.includes("-trans-") || question.id.startsWith("vijp-"))) return true;
  if (
    question?.prompt &&
    (question.prompt.includes("tiếng Nhật đúng nhất") ||
      question.prompt.includes("Chọn câu tiếng Nhật") ||
      question.prompt.includes("Dịch sang tiếng Nhật"))
  ) {
    return true;
  }
  if (
    question?.sentence &&
    (question.sentence.startsWith("Dịch sang tiếng Nhật") || !/[ぁ-んァ-ヶ一-龯]/.test(question.sentence))
  ) {
    return true;
  }
  return false;
}

/**
 * Trả về cách đọc Hiragana/Katakana cho câu hỏi luyện ngữ pháp.
 * - Tuyệt đối không hiển thị reading nếu câu hỏi là dạng dịch từ tiếng Việt sang tiếng Nhật
 *   hoặc câu đề bài là tiếng Việt thuần túy (tránh làm lộ đáp án).
 * - Nếu câu tiếng Nhật đã có sẵn trường `reading`, sử dụng trực tiếp.
 * - Nếu câu tiếng Nhật có chứa chữ Hán, tự động chuyển đổi sang Kana.
 * - Trả về `null` nếu câu không chứa tiếng Nhật hoặc không có chữ Hán cần phiên âm.
 */
export function getSentenceReading(
  sentence: string,
  question?: ExamQuestion | null,
): string | null {
  if (!sentence) return null;

  // 1. Kiểm tra câu hỏi dạng dịch tiếng Việt -> tiếng Nhật: tuyệt đối không hiện reading để tránh lộ đáp án
  if (isViToJpQuestion(sentence, question)) {
    return null;
  }

  // 2. Nếu câu là tiếng Việt thuần túy (không chứa ký tự tiếng Nhật), không cần reading
  if (!/[ぁ-んァ-ヶ一-龯]/.test(sentence)) {
    return null;
  }

  // 3. Ưu tiên reading được lưu sẵn trong question (dành cho câu tiếng Nhật có chỗ trống)
  if (question?.reading && question.reading.trim()) {
    return question.reading;
  }

  // 4. Nếu câu tiếng Nhật có chứa chữ Hán, tiến hành phiên âm sang Hiragana/Katakana
  if (hasKanji(sentence)) {
    const reading = toKana(sentence);
    return reading !== sentence ? reading : null;
  }

  // 5. Trường hợp câu toàn chữ Kana/Romaji
  return null;
}

/**
 * Trả về cách đọc Hiragana/Katakana cho một phương án lựa chọn (Option).
 * Chỉ trả về chuỗi đọc khi phương án đó có chứa chữ Hán (Kanji).
 * Nếu phương án chỉ toàn Hiragana (như trợ từ: より, ほど, に, で) thì trả về null.
 */
export function getOptionReading(option: string): string | null {
  if (!option || !hasKanji(option)) return null;

  const reading = toKana(option);
  return reading !== option ? reading : null;
}

// Khởi tạo bảng tra cứu chuyển đổi
const DICTIONARY_MAP = new Map<string, string>();

// 1. Nạp từ các ví dụ trong grammar.ts (nguồn chính xác tuyệt đối)
for (const lesson of grammar) {
  for (const point of lesson.points) {
    for (const ex of point.examples || []) {
      if (ex.jp && ex.reading && ex.jp !== ex.reading) {
        DICTIONARY_MAP.set(ex.jp, ex.reading);
      }
    }
  }
}

// 2. Nạp từ kho từ vựng vocabulary.ts
for (const v of vocabulary) {
  const w = v.word?.replace(/[（(][^）)]*[）)]/g, "").trim();
  const r = v.reading?.replace(/[（(][^）)]*[）)]/g, "").trim();
  if (w && r && /[一-龯]/.test(w)) {
    DICTIONARY_MAP.set(w, r);
  }
}

// 3. Nạp các cụm từ bổ sung
for (const [k, v] of EXTRA_TERMS) {
  DICTIONARY_MAP.set(k, v);
}

// 4. Nạp các chữ Hán đơn từ bảng chữ cái alphabet.ts
for (const a of alphabet) {
  if (a.type === "kanji" && a.char) {
    const k = a.kunyomi && a.kunyomi !== "-" ? a.kunyomi.split(".")[0] : null;
    const o = a.onyomi && a.onyomi !== "-" ? a.onyomi : null;
    const reading =
      k ||
      (o
        ? o.replace(/[\u30a1-\u30f6]/g, (m) =>
            String.fromCharCode(m.charCodeAt(0) - 0x60),
          )
        : null);
    if (reading && !DICTIONARY_MAP.has(a.char)) {
      DICTIONARY_MAP.set(a.char, reading);
    }
  }
}

// Sắp xếp các cụm từ theo độ dài giảm dần để ưu tiên ghép từ dài nhất (longest-match first)
const SORTED_ENTRIES = Array.from(DICTIONARY_MAP.entries()).sort(
  (a, b) => b[0].length - a[0].length,
);

/**
 * Chuyển đổi một chuỗi tiếng Nhật có chứa Kanji thành phiên âm Hiragana/Katakana.
 * Giữ nguyên các ký tự đặc biệt, dấu câu, chỗ trống điền từ như （　　）hoặc 〔〕.
 */
export function toKana(text: string): string {
  if (!text || !hasKanji(text)) return text;

  let result = text;
  for (const [kanjiPhrase, kanaReading] of SORTED_ENTRIES) {
    if (result.includes(kanjiPhrase)) {
      result = result.replaceAll(kanjiPhrase, kanaReading);
    }
    // Nếu chuỗi đã không còn chữ Hán nào nữa thì kết thúc sớm
    if (!hasKanji(result)) break;
  }
  return result;
}

/**
 * Trả về cách đọc Hiragana/Katakana cho câu hỏi luyện ngữ pháp.
 * - Nếu câu hỏi đã có sẵn trường `reading`, sử dụng trực tiếp.
 * - Nếu không, tìm trong ngân hàng ví dụ hoặc tự động chuyển đổi sang Kana.
 * - Trả về `null` nếu câu không chứa tiếng Nhật hoặc không có chữ Hán cần phiên âm.
 */
export function getSentenceReading(
  sentence: string,
  question?: ExamQuestion | null,
): string | null {
  if (!sentence) return null;

  // 1. Ưu tiên reading được lưu sẵn trong question
  if (question?.reading && question.reading.trim()) {
    return question.reading;
  }

  // 2. Nếu câu là tiếng Việt thuần túy (ví dụ: "Dịch sang tiếng Nhật: ..."), không cần reading
  if (!/[ぁ-んァ-ヶ一-龯]/.test(sentence)) {
    return null;
  }

  // 3. Nếu câu có chứa chữ Hán, tiến hành phiên âm sang Hiragana/Katakana
  if (hasKanji(sentence)) {
    const reading = toKana(sentence);
    return reading !== sentence ? reading : null;
  }

  // 4. Trường hợp câu toàn chữ Kana/Romaji
  return null;
}

/**
 * Trả về cách đọc Hiragana/Katakana cho một phương án lựa chọn (Option).
 * Chỉ trả về chuỗi đọc khi phương án đó có chứa chữ Hán (Kanji).
 * Nếu phương án chỉ toàn Hiragana (như trợ từ: より, ほど, に, で) thì trả về null.
 */
export function getOptionReading(option: string): string | null {
  if (!option || !hasKanji(option)) return null;

  const reading = toKana(option);
  return reading !== option ? reading : null;
}

// 1. Nạp từ các ví dụ trong grammar.ts (nguồn chính xác tuyệt đối)
for (const lesson of grammar) {
  for (const point of lesson.points) {
    for (const ex of point.examples || []) {
      if (ex.jp && ex.reading && ex.jp !== ex.reading) {
        DICTIONARY_MAP.set(ex.jp, ex.reading);
      }
    }
  }
}

// 2. Nạp từ kho từ vựng vocabulary.ts (xử lý cả ngoặc và dạng nguyên thể)
for (const v of vocabulary) {
  let w = v.word || "";
  let r = v.reading || "";
  if (w.includes("(") && w.includes(")") && /[一-龯]/.test(w)) {
    const match = w.match(/^([^\(]+)\s*\(([^)]+)\)/);
    if (match && /[ぁ-んァ-ヶ]/.test(match[1]) && /[一-龯]/.test(match[2])) {
      w = match[2];
      r = match[1];
    }
  }
  const cleanW = w.replace(/[［\[（\(][^］\]）\)]*[］\]）\)]/g, "").replace(/^[～~]/, "").trim();
  const cleanR = r.replace(/[［\[（\(][^］\]）\)]*[］\]）\)]/g, "").replace(/^[～~]/, "").trim();
  if (cleanW && cleanR && /[一-龯]/.test(cleanW) && /[ぁ-んァ-ヶ]/.test(cleanR)) {
    DICTIONARY_MAP.set(cleanW, cleanR);
  }
  if (w.includes("（お）") || w.includes("(お)")) {
    const x = w.replace(/（お）|\(お\)/g, "");
    const cleanX = x.replace(/[［\[（\(][^］\]）\)]*[］\]）\)]/g, "").trim();
    DICTIONARY_MAP.set("お" + cleanX, "お" + cleanR);
    DICTIONARY_MAP.set(cleanX, cleanR);
  }
  const dictFormMatch = w.match(/［([^］]+)］|\[([^\]]+)\]/);
  if (dictFormMatch) {
    const dictForm = dictFormMatch[1] || dictFormMatch[2];
    if (dictForm && /[一-龯]/.test(dictForm)) {
      if (cleanW.endsWith("ます") && cleanR.endsWith("ます")) {
        const stemR = cleanR.slice(0, -2);
        const stemW = cleanW.slice(0, -2);
        if (dictForm.startsWith(stemW)) {
          const suffix = dictForm.slice(stemW.length);
          DICTIONARY_MAP.set(dictForm, stemR + suffix);
        }
      }
    }
  }
}

// 3. Nạp các cụm từ bổ sung
for (const [k, v] of EXTRA_TERMS) {
  DICTIONARY_MAP.set(k, v);
}

// 4. Nạp các chữ Hán đơn từ bảng chữ cái alphabet.ts
for (const a of alphabet) {
  if (a.type === "kanji" && a.char) {
    const k = a.kunyomi && a.kunyomi !== "-" ? a.kunyomi.split(".")[0] : null;
    const o = a.onyomi && a.onyomi !== "-" ? a.onyomi : null;
    const reading =
      k ||
      (o
        ? o.replace(/[\u30a1-\u30f6]/g, (m) =>
            String.fromCharCode(m.charCodeAt(0) - 0x60),
          )
        : null);
    if (reading && !DICTIONARY_MAP.has(a.char)) {
      DICTIONARY_MAP.set(a.char, reading);
    }
  }
}

// Sắp xếp các cụm từ theo độ dài giảm dần để ưu tiên ghép từ dài nhất (longest-match first)
const SORTED_ENTRIES = Array.from(DICTIONARY_MAP.entries()).sort(
  (a, b) => b[0].length - a[0].length,
);

